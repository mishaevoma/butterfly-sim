// Trim every species preset with both aerodynamic models at the viewer's default resolution and
// write src/trims.js, which species.js merges in as each preset's trimmed kinematics.
// Usage: node tools/trim_species.mjs [species...]
import { writeFileSync, existsSync } from 'node:fs';
import { SPECIES } from '../src/species.js';
import { trim } from '../src/trim.js';

const RES = { M: 5, N: 10, stepsPerCycle: 40, wakeCycles: 2 };
const names = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(SPECIES);
const prev = existsSync(new URL('../src/trims.js', import.meta.url)) ? (await import('../src/trims.js')).TRIMS : {};
const out = { ...prev };
for (const name of names) {
  out[name] = {};
  for (const aero of ['qs', 'uvlm']) {
    const t0 = Date.now();
    const r = trim({ species: name, aero, useTrim: false, ...RES }, { cycles: aero === 'qs' ? 2 : 3, log: (l) => process.stderr.write(`  ${name}/${aero} it${l.iter} |r| ${l.norm.toFixed(4)}\n`) });
    const round = (v) => Math.round(v * 100) / 100;
    out[name][aero] = { phiAmp: round(r.x[0]), strokePlane: round(r.x[1]), psiMean: round(r.x[2]) };
    console.log(name, aero, JSON.stringify(out[name][aero]), 'converged', r.converged, 'residual', r.r.map((v) => v.toFixed(4)).join(' '), `${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
}
const body = `// Generated by tools/trim_species.mjs at ${RES.M}×${RES.N} panels, ${RES.stepsPerCycle} steps per beat, ${RES.wakeCycles}-beat wake:\n// kinematic trims for lift = weight, thrust = drag and zero mean pitching moment about the centre of mass.\nexport const TRIMS = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL('../src/trims.js', import.meta.url), body);
